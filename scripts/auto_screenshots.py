os.makedirs(SCREENSHOTS_DIR, exist_ok=True)

with sync_playwright() as p:
    # Запускаем браузер
    browser = p.chromium.launch(headless=False)
    page = browser.new_page()
    page.goto("http://localhost:8000")
    page.wait_for_load_state("networkidle")
    time.sleep(2)

    for i, q in enumerate(QUESTIONS, 1):
        print(f"\n[{i}/{len(QUESTIONS)}] Задаю вопрос: {q}")
        
        # 1. Вводим вопрос
        textarea = page.locator("#userInput")
        textarea.fill(q)
        page.locator("#sendBtn").click()

        # 2. ЖДЁМ ОКОНЧАНИЯ ГЕНЕРАЦИИ (строго ждём надпись "Завершено" в последней карточке)
        # Таймаут до 90 секунд, чтобы слабый ПК успел досчитать
        last_card = page.locator(".ai-card").last
        status_badge = last_card.locator("text=Завершено")
        
        try:
            status_badge.wait_for(state="visible", timeout=90000)
        except Exception:
            print(f"Превышено время ожидания для вопроса {i}, продолжаю...")

        # Небольшая пауза для завершения рендеринга Markdown
        time.sleep(1)

        # 3. ЕСЛИ ЕСТЬ ЦИТАТА СО СТРАНИЦЕЙ — РАСКРЫВАЕМ ЕЁ ДЛЯ КРАСОТЫ НА СКРИНЕ
        details = last_card.locator("details")
        if details.count() > 0:
            try:
                details.first.evaluate("el => el.open = true")
                time.sleep(0.5)
            except Exception:
                pass

        # 4. ДЕЛАЕМ СКРИНШОТ
        file_path = str(SCREENSHOTS_DIR / f"question_{i:02d}.png")
        last_card.screenshot(path=file_path)
        print(f" -> Готово! Скриншот сохранён: {file_path}")

    print("\n🎉 Все 40 скриншотов успешно созданы в папке screenshots/!")
